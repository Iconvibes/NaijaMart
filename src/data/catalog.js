export const formatNaira = (value) => `₦${value.toLocaleString('en-NG')}`

// "Phones & Tablets" -> "phones-tablets"
export const slugify = (name) =>
  name
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')

export const getCategoryBySlug = (slug) => categories.find((c) => c.slug === slug)
